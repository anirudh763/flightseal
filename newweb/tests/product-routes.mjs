import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const BASE = process.env.HASHWING_BASE_URL || 'http://127.0.0.1:3001';
const OUT = resolve(process.env.EVIDENCE_DIR || 'artifacts/verification/post-restart/product-browser');
mkdirSync(OUT, { recursive: true });
const require = createRequire(import.meta.url);
const axe = readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8');
const chromePath = process.env.CHROME_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined);
const browser = await chromium.launch({ headless: true, ...(chromePath ? { executablePath: chromePath } : {}) });
const context = await browser.newContext({ serviceWorkers: 'block' });
const errors = [];
const failures = [];
const checks = [];
const accessibility = [];
const pass = (name) => { checks.push(name); console.log(`PASS ${name}`); };
const page = await context.newPage();
context.on('page', (tab) => tab.on('pageerror', (error) => errors.push(String(error))));
page.on('pageerror', (error) => errors.push(String(error)));
page.on('response', (response) => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
const routeNames = [['/overview','Overview'], ['/workbench','Workbench'], ['/reports','Reports'], ['/settings','Settings']];
try {
  for (const [route, heading] of routeNames) {
    for (const width of [320, 375, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.goto(BASE + route);
      await page.getByRole('heading', { level: 1, name: heading }).waitFor();
      await page.reload();
      await page.getByRole('heading', { level: 1, name: heading }).waitFor();
      assert.match(await page.title(), new RegExp(heading));
      await page.evaluate(() => document.fonts.ready);
      const size = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
      assert.ok(size.scroll <= size.width + 1, `${route} ${width}px overflow: ${JSON.stringify(size)}`);
      await page.evaluate(axe);
      const result = await page.evaluate(() => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa', 'best-practice'] } }));
      accessibility.push({ route, width, violations: result.violations });
      assert.equal(result.violations.length, 0, `${route} ${width}px axe: ${JSON.stringify(result.violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target) })))}`);
      await page.screenshot({ path: `${OUT}/${route.slice(1) || 'upload'}-${width}.png`, fullPage: true });
      pass(`${route}: direct, refresh, title, overflow, axe ${width}px`);
    }
  }
  await page.goto(BASE + '/');
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Workbench', exact: true }).click();
  assert.equal(new URL(page.url()).pathname, '/workbench');
  await page.waitForFunction(() => document.activeElement.id === 'page-sandbox');
  await page.goBack();
  await page.getByRole('heading', { name: routeNames[0][1] }).waitFor();
  await page.goForward();
  await page.getByRole('heading', { name: routeNames[1][1] }).waitFor();
  pass('Back/Forward and navigation heading focus');
  await page.goto(BASE + '/');
  await page.locator('.brand').focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.locator(':focus').getAttribute('class'), 'skip-link');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator(':focus').getAttribute('id'), 'main');
  pass('Keyboard skip link');
  const second = await context.newPage();
  await second.goto(BASE + '/verify?sample=tampered&record=7');
  await second.locator('#result-heading').filter({ hasText: 'Tampered' }).waitFor();
  await page.goto(BASE + '/workbench?sample=intact&record=4');
  await page.locator('#result-heading').filter({ hasText: 'Intact' }).waitFor();
  const independentUrl = second.url();
  await page.getByRole('button', { name: 'Flip one payload byte', exact: true }).click();
  await page.locator('#result-heading').filter({ hasText: 'Tampered' }).waitFor();
  assert.equal(second.url(), independentUrl);
  assert.equal(new URL(second.url()).searchParams.get('record'), '7');
  await second.locator('#result-heading').filter({ hasText: 'Tampered' }).waitFor();
  pass('Two tabs preserve independent route/sample/record during mutation');
  await second.close();
  await page.goto(BASE + '/workbench');
  await page.getByLabel('Choose source or sealed log').setInputFiles({ name: 'product.tsv', mimeType: 'text/plain', buffer: Buffer.from('1000\tfirst\n2000\tsecond\n3000\tthird\n') });
  await page.getByRole('button', { name: 'Seal and verify', exact: true }).click();
  await page.locator('#result-heading').filter({ hasText: 'Intact' }).waitFor();
  await page.getByRole('button', { name: 'Download receipts', exact: true }).waitFor();
  await page.getByRole('checkbox', { name: 'I saved these files or no longer need them' }).check();
  pass('Real TSV seal and receipt output');
  await page.goto(BASE + '/verify');
  await page.getByLabel('HashWing / FlightSeal .fseal log').setInputFiles({ name: 'bad.fseal', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid log') });
  await page.getByRole('button', { name: 'Run check', exact: true }).click();
  await page.getByText('Record 0 · Invalid file header (bad-header)', { exact: true }).waitFor();
  await page.locator('#result-heading').filter({ hasText: 'Tampered' }).waitFor();
  pass('Malformed log failure is visible');
  await page.goto(BASE + '/reports');
  await page.getByText('Benchmarks and recovery evidence', {exact:true}).click();
  await page.getByRole('button', { name: 'Run verification benchmark' }).click();
  await page.getByText('Median elapsed', { exact: true }).waitFor();
  writeFileSync(`${OUT}/browser-benchmark.txt`, await page.locator('main').innerText());
  pass('Three native Wasm benchmark measurements');
  await page.goto(BASE + '/settings');
  await page.getByRole('button', { name: 'Refresh health' }).waitFor();
  await page.getByText('HTTP requests', { exact: true }).waitFor();
  assert.equal(await page.getByText('Unavailable', { exact: true }).count(), 0);
  await page.getByText('Raw metric samples', { exact: true }).click();
  assert.match(await page.locator('.metrics-text').innerText(), /# (HELP|TYPE)/);
  await page.getByRole('link', { name: 'Open metrics', exact: true }).waitFor();
  await page.getByRole('region', { name: 'Prometheus metric samples' }).focus();
  assert.equal(await page.locator(':focus').getAttribute('tabindex'), '0');
  await page.keyboard.press('ArrowDown');
  pass('Live health JSON and Prometheus samples');
  await page.route('**/readyz', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ status: 'not_ready' }) }));
  await page.getByRole('button', { name: 'Refresh health' }).click();
  await page.getByText('Not ready', { exact: true }).waitFor();
  pass('Controlled readiness failure is visible (browser response interception)');
  await page.route('**/metrics', (route) => route.fulfill({ status: 503, contentType: 'text/plain', body: 'Metrics dependency unavailable' }));
  await page.getByRole('button', { name: 'Refresh health' }).click();
  await page.getByText('Metrics unavailable. Start the local serving process and refresh health.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Open metrics', exact: true }).count(), 0);
  pass('Controlled metrics 503 hides the unavailable action');
  await page.route((url) => ['/healthz', '/readyz', '/api/system', '/metrics'].includes(url.pathname), (route) => route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><title>Static host</title>' }));
  await page.getByRole('button', { name: 'Refresh health' }).click();
  await page.getByText('Health data needs the local serving process. On static Pages hosting, these endpoints are unavailable.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Open metrics', exact: true }).count(), 0);
  pass('Controlled HTML endpoint responses hide the unavailable metrics action');
  assert.deepEqual(errors, []);
  const unexpectedFailures = failures.filter((item) => !item.startsWith('503 ') || !['/readyz', '/metrics'].some((path) => item.endsWith(path)));
  assert.deepEqual(unexpectedFailures, []);
  console.log(JSON.stringify({ checks: checks.length, passed: checks, runtimeErrors: errors, unexpectedHttpFailures: unexpectedFailures }, null, 2));
} finally {
  writeFileSync(`${OUT}/report.json`, JSON.stringify({ checks, accessibility, runtimeErrors: errors, httpFailures: failures }, null, 2));
  await browser.close();
}
